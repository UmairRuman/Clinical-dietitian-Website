// Generates supabase/migrations/0002_seed.sql from the in-repo content so copy lives in one place.
// Run: node --experimental-strip-types scripts/gen-seed.mjs
import { writeFileSync } from "node:fs";
import { serviceDetails, generalFaqs } from "../src/lib/content.ts";
import { profile, socials } from "../src/lib/identity.ts";

const q = (s) => (s == null ? "null" : `'${String(s).replaceAll("'", "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;

let sql = "-- GENERATED by scripts/gen-seed.mjs – edit src/lib/content.ts / seed.ts and regenerate.\n\n";

sql += `insert into profile (id, name, experience_line, tagline, bio, photo_alt, contact_email, contact_phone, whatsapp_number, address) values (1, ${q(profile.name)}, ${q(profile.experience)}, ${q(profile.tagline)}, ${q(profile.bio)}, ${q(profile.photoAlt)}, ${q(profile.email)}, ${q(profile.phone)}, null, null) on conflict (id) do nothing;\n\n`;

sql += `insert into settings (id, notification_email) values (1, ${q(profile.email)}) on conflict (id) do nothing;\n\n`;

const social = socials.map((s, i) => `('social', ${q(s.key)}, ${q(s.label)}, ${q(s.href)}, ${q(s.key)}, 'url', true, ${i})`);
const buttons = [
  ["about", "About Me", null, "about"],
  ["services", "Services", null, "services"],
  ["whatsapp-btn", "WhatsApp Me", socials.find((s) => s.key === "whatsapp").href, "url"],
  ["stories", "Client Testimonials", "/stories", "stories"],
  ["contact", "Contact / Email Me", null, "contact"],
].map(([k, l, u, a], i) => `('button', ${q(k)}, ${q(l)}, ${q(u)}, null, ${q(a)}, true, ${i})`);
sql += `insert into links (kind, key, label, url, icon, action, visible, sort_order) values\n  ${[...social, ...buttons].join(",\n  ")}\non conflict (key) do nothing;\n\n`;

sql += `insert into services (slug, title, short, icon, intro, who_for, approach, you_get, faqs, sort_order) values\n  ${serviceDetails
  .map((s, i) => `(${q(s.slug)}, ${q(s.title)}, ${q(s.short)}, ${q(s.icon)}, ${q(s.intro)}, ${arr(s.whoFor)}, ${arr(s.approach)}, ${arr(s.youGet)}, ${q(JSON.stringify(s.faqs))}::jsonb, ${i})`)
  .join(",\n  ")}\non conflict (slug) do nothing;\n\n`;

sql += `insert into faqs (question, answer, sort_order) values\n  ${generalFaqs.map((f, i) => `(${q(f.q)}, ${q(f.a)}, ${i})`).join(",\n  ")};\n`;

writeFileSync(new URL("../supabase/migrations/0002_seed.sql", import.meta.url), sql);
console.log("wrote supabase/migrations/0002_seed.sql");
